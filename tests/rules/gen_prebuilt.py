#!/usr/bin/env python3
"""Writes the third-party-haskell cell of the test project: a
haskell_prebuilt_library() for each of GHC's own packages that the fixtures
use (and their dependencies), and the tools.bzl that the toolchains cell
loads.

usage: gen_prebuilt.py GHC CELL_DIR

GHC is the compiler (ghc-pkg is found next to it). This stands in for
gen-haskell-prebuilt.py, which can't do it here: it skips
every package whose unit id ends in -inplace (the boot packages of GHC
9.10 and later, as built by hadrian), it maps only libraries under GHC's
libdir to the cell, and its tools.bzl lacks the fingerprints and tool
targets that toolchains/defaults.bzl and the other .bzl files load.
"""

import hashlib
import os
import re
import shutil
import subprocess
import sys

ROOTS = ["base", "template-haskell", "rts"]
FIELDS = "name,version,id,library-dirs,dynamic-library-dirs,hs-libraries,depends,include-dirs,extra-libraries"


def run(*cmd):
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout


def fields(ghc_pkg, uid):
    out = run(ghc_pkg, "field", "--ipid", uid, FIELDS)
    info, cur = {}, None
    for line in out.splitlines():
        m = re.match(r"^([\w-]+):\s*(.*)", line)
        if m:
            cur = m.group(1)
            info[cur] = m.group(2)
        elif cur and line[:1] in (" ", "\t"):
            info[cur] += " " + line.strip()
    return {k: v.split() for k, v in info.items()}


def main():
    ghc, cell = sys.argv[1], sys.argv[2]
    ghc_pkg = os.path.join(os.path.dirname(ghc), os.path.basename(ghc).replace("ghc", "ghc-pkg", 1))
    version = run(ghc, "--numeric-version").strip()
    ghc_info = run(ghc, "--info")
    libdir = os.path.realpath(run(ghc, "--print-libdir").strip())
    os.makedirs(os.path.join(cell, "external"), exist_ok=True)

    def link(name, target):
        path = os.path.join(cell, name)
        if os.path.lexists(path):
            os.remove(path)
        os.symlink(target, path)

    link("ghc-" + version, libdir)

    # Files outside the cell are reached through a symlink to their
    # directory, one per directory.
    roots = {}

    def rel(path):
        real = os.path.realpath(path)
        for d, name in roots.items():
            if real == d or real.startswith(d + "/"):
                return name + real[len(d):]
        name = "external/{}-{}".format(os.path.basename(real), hashlib.sha256(real.encode()).hexdigest()[:8])
        link(name, real)
        roots[real] = name
        return name

    # The closure of ROOTS, by unit id.
    pkgs = {}
    todo = [run(ghc_pkg, "field", r, "id", "--simple-output").split()[0] for r in ROOTS]
    while todo:
        uid = todo.pop()
        if uid in pkgs:
            continue
        pkgs[uid] = fields(ghc_pkg, uid)
        todo += pkgs[uid].get("depends", [])

    name_of = {uid: info["name"][0] for uid, info in pkgs.items()}
    out = ["# @generated by tests/rules/gen_prebuilt.py", ""]
    for uid, info in sorted(pkgs.items(), key=lambda p: name_of[p[0]]):
        name = name_of[uid]
        libdirs = info.get("library-dirs", [])
        dyndirs = info.get("dynamic-library-dirs", []) or libdirs
        static, prof, shared, ldflags = [], [], {}, []
        for stem in info.get("hs-libraries", []):
            for suffix, dest in ((".a", static), ("_p.a", prof)):
                for d in libdirs:
                    f = os.path.join(d, "lib" + stem + suffix)
                    if os.path.exists(f):
                        dest.append(rel(f))
                        break
            # GHC links its own rts in the way it was asked for.
            if name != "rts":
                so = "lib{}-ghc{}.so".format(stem, version)
                for d in dyndirs + libdirs:
                    if os.path.exists(os.path.join(d, so)):
                        shared[so] = rel(os.path.join(d, so))
                        break
        if name == "rts":
            ldflags = ["-L" + d for d in libdirs]
        ldflags += ["-l" + lib for lib in info.get("extra-libraries", [])]
        headers = [rel(d) for d in info.get("include-dirs", []) if os.path.isdir(d)] if name == "rts" else []
        out += [
            "haskell_prebuilt_library(",
            "    name = {!r},".format(name),
            "    version = {!r},".format(info["version"][0]),
            "    id = {!r},".format(uid),
            "    db = {!r},".format("ghc-{}/package.conf.d".format(version)),
            "    static_libs = {!r},".format(static),
            "    profiled_static_libs = {!r},".format(prof),
            "    pic_profiled_static_libs = {!r},".format(prof),
            "    shared_libs = {!r},".format(shared),
            "    cxx_header_dirs = {!r},".format(headers),
            "    exported_linker_flags = {!r},".format(ldflags),
            "    deps = {!r},".format(sorted(":" + name_of[d] for d in info.get("depends", []))),
            '    visibility = ["PUBLIC"],',
            ")",
            "",
        ]
    with open(os.path.join(cell, "BUCK"), "w") as f:
        f.write("\n".join(out))

    dynamic = re.search(r'\("GHC Dynamic",\s*"(\w+)"\)', ghc_info).group(1) == "YES"
    cc_version = run("cc", "--version")
    # The tools the toolchains run, by symlinks under toolchain/, as `cabal
    # buck2` makes them: GHC's, and the C toolchain on the PATH.
    bin_dir = os.path.dirname(os.path.realpath(ghc))
    os.makedirs(os.path.join(cell, "toolchain"), exist_ok=True)
    toolchain = {
        "GHC": os.path.join(bin_dir, "ghc"),
        "GHC_PKG": os.path.join(bin_dir, "ghc-pkg"),
        "HADDOCK": os.path.join(bin_dir, "haddock"),
        "HSC2HS": os.path.join(bin_dir, "hsc2hs"),
        "CC": shutil.which("cc"),
        "CXX": shutil.which("c++"),
        "LINKER": shutil.which("g++") or shutil.which("c++"),
    }
    tools = {
        **{k: "third-party/haskell/toolchain/" + k.lower() for k in toolchain},
        "CC_TYPE": "clang" if "clang" in cc_version else "gcc",
        "GHC_VERSION": version,
        # In every compile's environment, so that the action cache tells
        # one GHC (and C compiler) installation from another.
        "GHC_FINGERPRINT": version + "-" + hashlib.sha256(ghc_info.encode()).hexdigest()[:12],
        "CC_FINGERPRINT": run("cc", "-dumpmachine").strip() + "-" + hashlib.sha256(cc_version.encode()).hexdigest()[:12],
        "GHC_BIN_DIR": "third-party/haskell/ghc-bin",
        "GHC_DYNAMIC": dynamic,
        "ALEX": "third-party/haskell/missing",
        "HAPPY": "third-party/haskell/missing",
        "ALEX_TARGET": None,
        "ALEX_DATA": None,
        "ALEX_DATA_ENV": None,
        "HAPPY_TARGET": None,
        "HAPPY_DATA": None,
        "HAPPY_DATA_ENV": None,
        # The project builds no persistent worker of its own (see
        # toolchains/per_module_worker.bzl).
        "GHC_WORKER_TARGET": None,
    }
    with open(os.path.join(cell, "tools.bzl"), "w") as f:
        f.write("# @generated by tests/rules/gen_prebuilt.py\n\n")
        for k, v in tools.items():
            f.write("{} = {}\n".format(k, repr(v) if v is not None else "None"))
    link("ghc-bin", os.path.dirname(os.path.realpath(ghc)))
    for k, target in toolchain.items():
        link(os.path.join("toolchain", k.lower()), target)


if __name__ == "__main__":
    main()
